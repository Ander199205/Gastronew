const { chromium } = require('playwright');
require('fs').mkdirSync(__dirname + '/shots', { recursive: true });
const { install, db } = require('./mock.cjs');
const B = 'http://localhost:4173';
const shot = (p, n) => p.screenshot({ path: `${__dirname}/shots/${n}.png`, fullPage: false });
(async () => {
  const browser = await chromium.launch();
  const errors = [];
  const guestCtx = await browser.newContext({ viewport: { width: 390, height: 844 }, locale: 'es-ES' });
  await install(guestCtx);
  const g = await guestCtx.newPage();
  g.on('pageerror', e => errors.push('guest: ' + e.message));
  g.on('console', m => m.type() === 'error' && errors.push('guest console: ' + m.text()));
  await g.goto(`${B}/r/casalucia/mesa/7?k=key7`);
  await g.getByText('Hacer check-in', { exact: false }).first().waitFor({ timeout: 8000 }).catch(() => {});
  await shot(g, '01-checkin');
  await g.fill('input[autocomplete=given-name]', 'Ana');
  await g.locator('.g-checkin .g-btn').click();
  await g.locator('.g-nav').waitFor();
  await g.locator('.g-add').first().click();
  await g.locator('.g-add').nth(3).click();
  await shot(g, '02-menu');
  await g.locator('.g-cartbar').click();
  await shot(g, '03-cart');
  await g.locator('.g-sheet .g-btn').click();
  await g.waitForTimeout(600);
  await shot(g, '04-sent');
  await g.locator('.g-nav button').nth(1).click();
  await g.locator('.g-chips button').first().click();
  await g.waitForTimeout(500);
  await shot(g, '05-chat');

  // personal
  const sCtx = await browser.newContext({ viewport: { width: 1280, height: 800 } });
  await install(sCtx);
  const s = await sCtx.newPage();
  s.on('pageerror', e => errors.push('staff: ' + e.message));
  await s.goto(`${B}/app`);
  await s.fill('input[type=email]', 'carmen@test'); await s.fill('input[type=password]', 'x');
  await s.click('button.s-btn.primary');
  await s.locator('.s-table').first().waitFor();
  await shot(s, '10-tables');
  await s.locator('.s-table', { hasText: '7' }).filter({ hasText: 'Ana' }).click();
  await s.waitForTimeout(400);
  await s.locator('.s-chips button').first().click();
  await s.waitForTimeout(400);
  await shot(s, '11-table7');
  await s.getByText('Bestätigen → Küche').first().click();
  await s.waitForTimeout(400);
  await s.click('a[href="/app/kueche"]');
  await s.waitForTimeout(400);
  await shot(s, '12-kitchen');
  await s.getByText('Fertig ✓').first().click();
  // pedido de papel en mesa 5
  await s.click('a[href="/app/tische"]');
  await s.locator('.s-table').nth(4).click();
  await s.getByText('Bestellung aufnehmen').click();
  await s.locator('.s-pad-item .p').first().click();
  await s.locator('.s-pad-item .p').first().click();
  await shot(s, '13-pad');
  await s.locator('.s-pad .s-btn.primary.wide').click();
  await s.waitForTimeout(500);
  await s.click('a[href="/app/bestellungen"]');
  await s.waitForTimeout(400);
  await shot(s, '14-orders');
  await s.click('a[href="/app/qr"]').catch(() => {});

  // cliente ve estado y pide cuenta
  await g.waitForTimeout(4500);
  await g.locator('.g-nav button').nth(0).click();
  await shot(g, '06-status');
  await g.locator('.g-nav button').nth(2).click();
  await g.locator('.g-seg button').nth(2).click();
  await shot(g, '07-bill');
  await g.locator('.g-main, main .g-btn').last().click();
  await g.waitForTimeout(600);
  await shot(g, '08-billreq');
  // camarero cierra
  await s.click('a[href="/app/tische"]');
  await s.locator('.s-table.st-bill').click();
  s.on('dialog', d => d.accept());
  await s.getByText('Bezahlt · Tisch freigeben').click();
  await s.waitForTimeout(500);
  await g.waitForTimeout(4500);
  await shot(g, '09-thanks');
  console.log('orders', db.orders.map(o => `${o.number}:${o.status}:${o.source}`).join(' '), 'visits', db.visits.map(v => v.status).join(','));
  console.log('ERRORS', errors);
  await browser.close();
})().catch(e => { console.error('FAIL', e.message); process.exit(1); });
